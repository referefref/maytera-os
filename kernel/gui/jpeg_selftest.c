// #332 progressive: decode an embedded JPEG in-kernel (via the REAL image_load_jpeg,
// which under -DRUST_JPEG_ENTROPY runs the Rust fixed-point IDCT) and check dims +
// 5 sample pixels against PIL/libjpeg ground truth. Prints result to serial.
static int jpeg_st_check(const char *tag, const unsigned char *buf, uint32_t n,
                         uint32_t ew, uint32_t eh, int tol, const int gt[5][3]) {
    image_t img; img.pixels = 0; img.width = 0; img.height = 0;
    int r = image_load_jpeg(buf, n, &img);
    if (r != JPEG_SUCCESS || !img.pixels || img.width != ew || img.height != eh) {
        kprintf("[JPGTEST] %s: FAIL ret=%d (%s) w=%u h=%u (expected %ux%u)\n",
                tag, r, jpeg_error_string(r), img.width, img.height, ew, eh);
        if (img.pixels) kfree(img.pixels);
        return 0;
    }
    int cx[5] = {0, (int)ew/4, (int)ew/2, 3*(int)ew/4, (int)ew-1};
    int cy[5] = {0, (int)eh/4, (int)eh/2, 3*(int)eh/4, (int)eh-1};
    int maxd = 0, uniform = 1; uint32_t first = img.pixels[0];
    for (uint32_t i = 1; i < img.width*img.height; i++) if (img.pixels[i]!=first){uniform=0;break;}
    for (int s = 0; s < 5; s++) {
        uint32_t v = img.pixels[(uint32_t)cy[s]*img.width + cx[s]];
        int R=(v>>16)&0xFF, G=(v>>8)&0xFF, B=v&0xFF;
        int dr=R-gt[s][0]; if(dr<0)dr=-dr;
        int dg=G-gt[s][1]; if(dg<0)dg=-dg;
        int db=B-gt[s][2]; if(db<0)db=-db;
        int md=dr>dg?dr:dg; md=md>db?md:db; if(md>maxd)maxd=md;
        kprintf("[JPGTEST]   %s (%d,%d) got(%d,%d,%d) exp(%d,%d,%d) d=%d\n",
                tag, cx[s],cy[s], R,G,B, gt[s][0],gt[s][1],gt[s][2], md);
    }
    int pass = (!uniform) && (maxd <= tol);
    kprintf("[JPGTEST] %s: %s maxdelta=%d tol=%d uniform=%d\n",
            tag, pass?"PASS":"FAIL", maxd, tol, uniform);
    kfree(img.pixels);
    return pass;
}

static void jpeg_selftest_worker(void *arg) {
    (void)arg;
    proc_sleep(12000);   // let drivers + desktop settle
    uint32_t cfgsz = 0;
    char *cfg = (char *)fat_read_file(&g_fat_fs, "/CONFIG/JPGTEST.CFG", &cfgsz);
    if (!cfg) return;    // no flag -> silent no-op
    kfree(cfg);

    kprintf_set_dual_output(1);
    kprintf("\n========== JPEG DECODER SELFTEST (#332) ==========\n");
    kprintf("[JPGTEST] embedded baseline JPEG: %u bytes, is_jpeg=%d\n",
            (unsigned)sizeof(jpeg_selftest_img),
            image_is_jpeg(jpeg_selftest_img, sizeof(jpeg_selftest_img)));

    image_t img;
    img.pixels = 0; img.width = 0; img.height = 0;
    int r = image_load_jpeg(jpeg_selftest_img, sizeof(jpeg_selftest_img), &img);

    if (r == JPEG_SUCCESS && img.pixels && img.width && img.height) {
        uint32_t sum = 2166136261u;     // FNV-1a-ish rolling checksum
        for (uint32_t i = 0; i < img.width * img.height; i++) {
            sum ^= img.pixels[i];
            sum *= 16777619u;
        }
        kprintf("[JPGTEST] decode OK: ret=%d w=%u h=%u checksum=0x%08x\n",
                r, img.width, img.height, sum);
        kprintf("[JPGTEST] RESULT: PASS (no longer returns -1)\n");
        kfree(img.pixels);
    } else {
        kprintf("[JPGTEST] decode FAILED: ret=%d (%s) w=%u h=%u\n",
                r, jpeg_error_string(r), img.width, img.height);
        kprintf("[JPGTEST] RESULT: FAIL\n");
        if (img.pixels) kfree(img.pixels);
    }
    kprintf("[JPGTEST] --- progressive (SOF2) decode tests ---\n");
    {
        static const int gt_p4[5][3] = {{0,0,0},{1,0,0},{249,249,221},{0,0,0},{0,0,0}};
        static const int gt_p1[5][3] = {{73,74,78},{55,54,52},{23,48,26},{50,50,52},{73,74,76}};
        int p4 = jpeg_st_check("P4-prog-4:2:0-128x128", jpeg_prog_p4, sizeof(jpeg_prog_p4), 128,128, 4, gt_p4);
        int p1 = jpeg_st_check("P1-prog-4:4:4-32x32",   jpeg_prog_p1, sizeof(jpeg_prog_p1), 32,32,  3, gt_p1);
        kprintf("[JPGTEST] PROGRESSIVE RESULT: %s\n", (p4 && p1) ? "PASS" : "FAIL");
    }
    kprintf("========== JPEG DECODER SELFTEST: DONE ==========\n");
    kprintf_set_dual_output(0);
}

void jpeg_start_deferred_selftest(void) {
    proc_create_ex("jpgtest", jpeg_selftest_worker, 0, 1, 256 * 1024);
}
