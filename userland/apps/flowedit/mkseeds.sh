#!/bin/sh
# mkseeds.sh - generate seeds.h from userland/apps/flowrun/examples/*.yml.
#
# WHY THIS EXISTS. The bundled example workflows used to be HAND-COPIED into
# flowedit/main.c as SEED_* C string literals, trimmed and rewritten by hand. The
# examples themselves live in userland/apps/flowrun/examples/, which is also what
# the runner's host test executes. Two copies of the same catalog, maintained by
# hand, drifted exactly as you would expect: examples/visiongame.yml, the Game
# Boy AI-vision demo, had NO seed at all, so it existed in the repo, was covered
# by the host test, and was NOT PRESENT ON ANY SHIPPED IMAGE. A user opening Flow
# could not load it because it was not there. Measured on golden 2539: the image
# has no /CONFIG/WORKFLOWS directory at all; the editor creates and seeds it on
# first run, from this list.
#
# So the list is now GENERATED from the directory. Adding a .yml to examples/ ships
# it, and the seeded copy is BYTE-FOR-BYTE the repo file, comments and all, which
# is also what Library > Fork promises.
set -e
SRC="${1:-../flowrun/examples}"
OUT="${2:-seeds.h}"

{
  echo "// GENERATED by mkseeds.sh from $SRC/*.yml - DO NOT EDIT."
  echo "// The example catalog has ONE source of truth: the .yml files the runner's"
  echo "// host test also executes. Add a file there and it ships."
  echo "#ifndef MAYTERA_FLOW_SEEDS_H"
  echo "#define MAYTERA_FLOW_SEEDS_H"
  echo ""
  for f in "$SRC"/*.yml; do
    b=$(basename "$f" .yml)
    sym=$(echo "$b" | tr 'a-z-' 'A-Z_')
    echo "static const char SEED_$sym[] ="
    awk '{ line=$0; gsub(/\\/,"\\\\",line); gsub(/"/,"\\\"",line);
           printf "    \"%s\\n\"\n", line }' "$f"
    echo "    ;"
    echo ""
  done
  echo "typedef struct { const char *name; const char *yml; } flow_seed_t;"
  echo "static const flow_seed_t FLOW_SEEDS[] = {"
  for f in "$SRC"/*.yml; do
    b=$(basename "$f" .yml)
    sym=$(echo "$b" | tr 'a-z-' 'A-Z_')
    echo "    { \"$b\", SEED_$sym },"
  done
  echo "};"
  echo "#define FLOW_NSEEDS ((int)(sizeof(FLOW_SEEDS)/sizeof(FLOW_SEEDS[0])))"
  echo ""
  echo "#endif // MAYTERA_FLOW_SEEDS_H"
} > "$OUT"
echo "mkseeds: wrote $OUT ($(ls -l "$OUT" | awk '{print $5}') bytes, $(ls "$SRC"/*.yml | wc -l) examples)"
