// font.rs - gbemu's own tiny 5x7 bitmap pixel font, for the in-LCD ROM
// navigator (owner feedback, 2026-09-06: the navigator must stay true to the
// Game Boy pixel design, no antialiased TTF). Hand-authored block glyphs,
// clean-room, not derived from any existing font asset. Deliberately narrow
// coverage: uppercase A-Z, 0-9, space, and the punctuation the navigator
// actually needs (. - / : < > ! ' ( ) _). Anything outside that set draws as
// a blank cell rather than panicking, since ROM titles (Game Boy header
// titles, and whatever the owner names a preview JPG) are not guaranteed to
// be pure ASCII.
//
// Each glyph is 7 rows of 5 columns, one row per u8 with the column bits in
// bits 4..0 (bit 4 = leftmost column, bit 0 = rightmost).

pub const GLYPH_W: i32 = 5;
pub const GLYPH_H: i32 = 7;

fn glyph_rows(c: u8) -> [u8; 7] {
    let ch = (c as char).to_ascii_uppercase();
    match ch {
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0F, 0x10, 0x10, 0x10, 0x10, 0x10, 0x0F],
        'D' => [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0F, 0x10, 0x10, 0x17, 0x11, 0x11, 0x0F],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x1F],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x11, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x1F],
        '2' => [0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F],
        '3' => [0x1E, 0x01, 0x01, 0x0E, 0x01, 0x01, 0x1E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x10, 0x1E, 0x01, 0x01, 0x1E],
        '6' => [0x0E, 0x10, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x01, 0x0E],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x04],
        '-' => [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
        '/' => [0x01, 0x02, 0x04, 0x04, 0x04, 0x08, 0x10],
        ':' => [0x00, 0x04, 0x00, 0x00, 0x00, 0x04, 0x00],
        '<' => [0x02, 0x04, 0x08, 0x10, 0x08, 0x04, 0x02],
        '>' => [0x08, 0x04, 0x02, 0x01, 0x02, 0x04, 0x08],
        '!' => [0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04],
        '\'' => [0x04, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00],
        '(' => [0x04, 0x08, 0x10, 0x10, 0x10, 0x08, 0x04],
        ')' => [0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08],
        '_' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1F],
        _ => [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00], // space and anything unmapped: blank cell
    }
}

// Draws one glyph at (x, y) top-left, `scale` pixels per glyph-pixel, into a
// buf_w x buf_h u32 buffer. Fully clipped: any glyph pixel that lands outside
// the buffer is silently skipped (this is the one drawing primitive the whole
// navigator screen routes through, so clipping lives here once).
pub fn draw_char(buf: &mut [u32], buf_w: i32, buf_h: i32, x: i32, y: i32, c: u8, color: u32, scale: i32) {
    let rows = glyph_rows(c);
    let scale = if scale < 1 { 1 } else { scale };
    for (row, bits) in rows.iter().enumerate() {
        let py = y + (row as i32) * scale;
        if py + scale <= 0 || py >= buf_h {
            continue;
        }
        for col in 0..5i32 {
            if bits & (1 << (4 - col)) == 0 {
                continue;
            }
            let px = x + col * scale;
            if px + scale <= 0 || px >= buf_w {
                continue;
            }
            for sy in 0..scale {
                let yy = py + sy;
                if yy < 0 || yy >= buf_h {
                    continue;
                }
                for sx in 0..scale {
                    let xx = px + sx;
                    if xx < 0 || xx >= buf_w {
                        continue;
                    }
                    buf[(yy as usize) * (buf_w as usize) + (xx as usize)] = color;
                }
            }
        }
    }
}

// Draws a whole ASCII string left to right, one glyph-cell (GLYPH_W+1 columns,
// scaled) apart. Returns the pixel width consumed, so callers can centre text.
pub fn draw_text(buf: &mut [u32], buf_w: i32, buf_h: i32, x: i32, y: i32, s: &[u8], color: u32, scale: i32) -> i32 {
    let cell_w = (GLYPH_W + 1) * scale;
    let mut cx = x;
    for &c in s.iter() {
        draw_char(buf, buf_w, buf_h, cx, y, c, color, scale);
        cx += cell_w;
    }
    cx - x - scale // drop the trailing inter-glyph gap from the reported width
}

pub fn text_width(s: &[u8], scale: i32) -> i32 {
    if s.is_empty() {
        return 0;
    }
    let cell_w = (GLYPH_W + 1) * scale;
    (s.len() as i32) * cell_w - scale
}
